# Aliases for backward compatibility with existing templates using dot notation
_ALIASES: dict[str, str] = {}
for key in list(LUCIDE_ICONS.keys()):
    dotted = key.replace("-", ".")
    if dotted != key:
        _ALIASES[dotted] = key
    underscored = key.replace("-", "_")
    if underscored != key:
        _ALIASES[underscored] = key


def get_icon_svg_inner(key: str) -> str | None:
    """Return the inner SVG content for a given icon key, or None if not found."""
    import re
    normalized = re.sub(r"[^a-zA-Z0-9]", "-", (key or "").strip())
    normalized = re.sub(r"-{2,}", "-", normalized).strip("-").lower()

    if normalized in LUCIDE_ICONS:
        return LUCIDE_ICONS[normalized]

    # Try alias lookup
    dotted = (key or "").strip()
    if dotted in _ALIASES:
        return LUCIDE_ICONS.get(_ALIASES[dotted])
    if normalized in _ALIASES:
        return LUCIDE_ICONS.get(_ALIASES[normalized])

    return None
